/// Легкий шар перекладу. Ключ — українське джерело (uk = identity), тож
/// невимкнені рядки безпечно показують українською. Реактивність: gLang
/// встановлюється в KavioApp з локалі, а MaterialApp має key(gLang) — при зміні
/// мови все дерево перебудовується й t() повертає нову мову.
String gLang = 'uk';

String t(String uk) {
  if (gLang == 'uk') return uk;
  final m = gLang == 'en' ? _en : _ru;
  return m[uk] ?? uk;
}

/// З підстановкою {n}/{name} тощо.
String tp(String uk, Map<String, Object> args) {
  var s = t(uk);
  args.forEach((k, v) => s = s.replaceAll('{$k}', '$v'));
  return s;
}


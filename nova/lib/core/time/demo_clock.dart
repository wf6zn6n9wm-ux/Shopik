/// Демо-годинник вітрини. Знімки екранів рендеряться в CI у довільний час доби
/// (UTC), тож «зараз» прив'язуємо до приємної денної точки — щоб дашборд і
/// календар завжди виглядали як на макетах (наступний клієнт за 25 хв, денні
/// вільні вікна). У продукті замінюється на реальний годинник.
DateTime demoNow() {
  final n = DateTime.now();
  return DateTime(n.year, n.month, n.day, 14, 20);
}

/// Сьогоднішня опівніч (для прив'язки записів того ж дня).
DateTime demoToday() {
  final n = DateTime.now();
  return DateTime(n.year, n.month, n.day);
}

function interpolate(str, vars){
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars[k] === undefined ? m : String(vars[k])));
}

/* Створює перекладач для мови. t() ніколи не кидає й ніколи не
   повертає порожній рядок: немає ключа → uk → сам ключ. */
function makeT(lang){
  const dict = DICT[lang] || DICT.uk;
  const t = (key, vars) => {
    const raw = dict[key] !== undefined ? dict[key] : (DICT.uk[key] !== undefined ? DICT.uk[key] : key);
    return interpolate(raw, vars);
  };
  t.lang = lang;
  t.cal = CAL[lang] || CAL.uk;
  t.tag = (LANGS.find(l => l.id === lang) || LANGS[0]).tag;
  /* plural('lesson', 5) → «5 занять» */
  t.plural = (kind, n) => {
    const forms = (PLURALS[kind] || {})[lang] || (PLURALS[kind] || {}).uk;
    if (!forms) return String(n);
    const idx = lang === 'en' ? (Math.abs(n) === 1 ? 0 : 1) : slavicForm(Math.abs(n));
    return interpolate(forms[Math.min(idx, forms.length - 1)], {n});
  };
  return t;
}


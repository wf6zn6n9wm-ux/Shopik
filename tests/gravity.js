function мерки(тр) {
  const p = тр.точки;
  let яма = 0, угол = 0;
  for (let i = 1; i < p.length; i++) {
    const dx = p[i].x - p[i - 1].x, dy = p[i].y - p[i - 1].y;
    if (dx > 0.2) угол = Math.max(угол, Math.abs(Math.atan2(dy, dx)));
    if (dx < 0.2 && dy < -1) {
      const дно = p[i].y; let j = i;
      while (j < p.length - 1 && p[j + 1].y < дно + 0.5) j++;
      яма = Math.max(яма, p[j].x - p[i].x);
    }
  }
  return { яма, угол };
}

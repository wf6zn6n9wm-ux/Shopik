/* ── 5. Заезд до финиша ───────────────────────────────────── */
console.log('\nзаезд');
/* Простой автопилот: газ + наклон против опрокидывания. Он не обязан
   пройти всё, но на первой трассе должен уехать далеко и по времени. */
function автозаезд(л, секунд) {
  const тр = сделатьТрассу(л.seed, л.diff);
  const b = сделатьБайк(тр);
  const dt = 1 / 120;
  for (let i = 0; i < секунд * 120; i++) {
    if (b.упал || b.финиш) break;
    const ang = Math.atan2(b.п.y - b.з.y, b.п.x - b.з.x);
    const воздух = !b.з.на && !b.п.на;
    const вх = {
      gas: воздух ? 0 : 1,
      brake: 0,
      lean: воздух ? (ang > 0.25 ? -1 : ang < -0.35 ? 1 : 0) : (ang > 0.7 ? -1 : 0)
    };
    шаг(b, тр, вх, dt);
  }
  return { b, тр, доля: (b.з.x - тр.старт) / (тр.финиш - тр.старт) };
}
const r0 = автозаезд(уровень(0, 0), 60);

/* Сложность растёт: у «Профи» рельеф резче, чем у «Новичка». */
function крутизна(тр) {
  let s = 0, n = 0;
  for (let i = 1; i < тр.точки.length; i++) {
    const dx = тр.точки[i].x - тр.точки[i - 1].x;
    const dy = тр.точки[i].y - тр.точки[i - 1].y;
    if (dx > 0.2) { s += Math.abs(dy / dx); n++; }
  }
  return s / n;
}
const лёгкие = [0, 1, 2].map((н) => крутизна(сделатьТрассу(уровень(0, н).seed, уровень(0, н).diff)));
const злые = [3, 4, 5].map((н) => крутизна(сделатьТрассу(уровень(2, н).seed, уровень(2, н).diff)));
const ср = (a) => a.reduce((x, y) => x + y, 0) / a.length;
ок(ср(злые) > ср(лёгкие) * 1.2, 'у «Профи» рельеф круче, чем у «Новичка»');


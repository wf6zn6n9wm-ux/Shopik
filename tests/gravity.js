бФ.п.x = бФ.з.x + ФИЗ.БАЗА; бФ.п.y = земля(трФ, бФ.п.x) + ФИЗ.R;
for (let i = 0; i < 240; i++) { шаг(бФ, трФ, газ, 1 / 120); if (бФ.финиш) break; }

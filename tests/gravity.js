/* Отвесные стенки ям когда-то работали как праща: байк разгонялся до 300 м/с.
   Гоняем бота по всем трассам и следим за пиковой скоростью. */
function пиковая(л) {
  const тр = сделатьТрассу(л.seed, л.diff);
  const b = сделатьБайк(тр);
  let v = 0;
  for (let i = 0; i < 90 * 120; i++) {
    if (b.финиш) break;
    const ang = Math.atan2(b.п.y - b.з.y, b.п.x - b.з.x);
    const воздух = !b.з.на && !b.п.на;
    шаг(b, тр, { gas: 1, brake: 0, lean: ang > 0.5 ? -1 : воздух ? -1 : 0 }, 1 / 120);
    v = Math.max(v, Math.hypot(b.з.vx, b.з.vy));
  }
  return v;
}
let пик = 0;
for (const л of всеТрассы) пик = Math.max(пик, пиковая(л));

/* ── 6. Трассы проходимы ──────────────────────────────────── */
console.log('\nпроходимость');
/* Ямы должны перепрыгиваться на разумной скорости, а склоны — не быть стенами.
   Дальность прыжка с трамплина под 25°: v²·sin(2α)/g. */
function мерки(тр) {
  const p = тр.точки;
  let яма = 0, угол = 0;
  for (let i = 1; i < p.length; i++) {
    const dx = p[i].x - p[i - 1].x, dy = p[i].y - p[i - 1].y;
    if (dx > 0.2) угол = Math.max(угол, Math.abs(Math.atan2(dy, dx)));
    if (dx < 0.2 && dy < -1) {
      const дно = p[i].y; let j = i;
      while (j < p.length - 1 && p[j + 1].y < дно + 0.5) j++;
      яма = Math.max(яма, p[j].x - p[i].x);
    }
  }
  return { яма, угол };
}
const дальность = (v) => v * v * Math.sin(2 * 0.44) / ФИЗ.G;
let ямыОк = true, склоныОк = true, самаяЯма = 0, самыйУгол = 0;
for (const л of всеТрассы) {
  const м = мерки(сделатьТрассу(л.seed, л.diff));
  самаяЯма = Math.max(самаяЯма, м.яма); самыйУгол = Math.max(самыйУгол, м.угол);
  if (м.яма > дальность(ФИЗ.МАКС * 0.8)) ямыОк = false;
  if (м.угол > 1.05) склоныОк = false;      // круче 60° — уже стена
}
ок(ямыОк, 'самая широкая яма (' + самаяЯма.toFixed(1) + ' м) перепрыгивается, не разгоняясь до предела');
ок(склоныОк, 'нет склонов круче 60° (максимум ' + (самыйУгол * 57.3).toFixed(0) + '°)');


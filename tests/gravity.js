for (let i = 0; i < 360; i++) шаг(бк, тр0, газ, 1 / 120);
ок(бк.з.x > x0 + 10, 'на полном газу за 3 с проезжает больше 10 м (' + бк.з.x.toFixed(1) + ' м)');
ок(бк.макс > 5 && бк.макс < ФИЗ.МАКС * 1.6, 'скорость в разумных пределах (' + бк.макс.toFixed(1) + ' м/с)');
ок(конечно(бк.з.x) && конечно(бк.п.y), 'физика не разошлась в NaN');

const дох = бк.з.x;
const торм = { gas: 0, brake: 1, lean: 0 };
let v0 = Math.hypot(бк.з.vx, бк.з.vy);
for (let i = 0; i < 120; i++) шаг(бк, тр0, торм, 1 / 120);
ок(Math.hypot(бк.з.vx, бк.з.vy) < v0 * 0.6, 'тормоз действительно тормозит');
ок(бк.з.x > дох - 1, 'при торможении не отбрасывает назад');


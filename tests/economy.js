/* Экономика игр — по формулам из самого файла, а не по памяти: вытаскиваем
   строки кода и моделируем именно их, иначе расчёт разойдётся с игрой. */
const { исходник, Отчёт } = require('./helpers');

const src = исходник();
const взять = (re, что) => { const m = src.match(re); if (!m) throw new Error('не нашёл: ' + что); return m; };
const о = new Отчёт('economy');

о.раздел('Краш');
const ДОЛЯ = +взять(/var ДОЛЯ=([\d.]+)/, 'доля дома')[1];
const ПОТОЛОК = +взять(/ПОТОЛОК=(\d+)/, 'потолок')[1];
const обрыв = () => {
  const v = Math.min(ПОТОЛОК, ДОЛЯ / Math.max(1e-9, Math.random()));
  return v < 1 ? 1 : +v.toFixed(2);
};
let ровно = true;
for (const x of [1.01, 1.2, 1.5, 2, 3, 5, 10, 20]) {
  const N = 200000; let дошло = 0;
  for (let i = 0; i < N; i++) if (обрыв() >= x) дошло++;
  const возврат = дошло / N * x;
  const хорошо = Math.abs(возврат - ДОЛЯ) < 0.03;
  if (!хорошо) ровно = false;
  о.замечание('забрать на ×' + String(x).padEnd(5) + ' → возврат ' + (возврат * 100).toFixed(0) + '%');
}
о.проверка('возврат одинаков на любой точке и равен ' + (ДОЛЯ * 100) + '%', ровно);
{
  const N = 200000; let сразу = 0;
  for (let i = 0; i < N; i++) if (обрыв() <= 1) сразу++;
  const доля = сразу / N;
  о.проверка('доля дома выходит мгновенным обрывом', Math.abs(доля - (1 - ДОЛЯ)) < 0.01,
    (доля * 100).toFixed(1) + '% раундов рвутся на ×1.00');
}

о.раздел('кейсы');
const ODDS = JSON.parse(взять(/var ODDS=(\[[\d,]+\])/, 'шансы')[1]);
о.проверка('шансы дают ровно 100%', ODDS.reduce((a, b) => a + b, 0) === 100, ODDS.join('+'));
const КЕЙСЫ = [...src.matchAll(/\{id:'(\w+)',\s*name:'\w+',\s*price:(\d+),[^}]*drops:\[([\d,]+)\]/g)]
  .map(m => ({ id: m[1], цена: +m[2], v: m[3].split(',').map(Number) })).filter(k => k.цена);
const возвраты = КЕЙСЫ.map(k => {
  const E = k.v.reduce((s, v, i) => s + v * ODDS[i] / 100, 0);
  о.замечание(k.id.padEnd(8) + ' цена ' + String(k.цена).padStart(4) + ' → в среднем ' +
    E.toFixed(2) + ' ★, возврат ' + (E / k.цена * 100).toFixed(1) + '%');
  return E / k.цена;
});
const разброс = Math.max(...возвраты) - Math.min(...возвраты);
о.проверка('возврат одинаков на всех кейсах', разброс < 0.01, 'разброс ' + (разброс * 100).toFixed(1) + ' п.п.');
о.проверка('дом в плюсе, но не грабит', возвраты.every(v => v > 0.8 && v < 0.95),
  (возвраты[0] * 100).toFixed(1) + '%');

о.раздел('ПВП');
const КОМИССИЯ = +взять(/var КОМИССИЯ=([\d.]+)/, 'комиссия')[1];
{
  const N = 300000; let вложил = 0, забрал = 0;
  for (let i = 0; i < N; i++) {
    const моя = 100, чужие = [50, 100, 250, 500].slice(0, 1 + Math.floor(Math.random() * 4));
    const банк = моя + чужие.reduce((a, b) => a + b, 0);
    вложил += моя;
    if (Math.random() * банк <= моя) забрал += Math.floor(банк * (1 - КОМИССИЯ));
  }
  const возврат = забрал / вложил;
  о.проверка('возврат равен 1 минус комиссия', Math.abs(возврат - (1 - КОМИССИЯ)) < 0.02,
    (возврат * 100).toFixed(1) + '% при комиссии ' + (КОМИССИЯ * 100) + '%');
}

о.раздел('майнинг: обязательства');
const BASE = +взять(/var BASE_YIELD = ([\d.]+)/, 'база')[1];
const BOOSTS = [...взять(/var BOOSTS=\[([\s\S]*?)\];/, 'бусты')[1]
  .matchAll(/\{y:([\d.]+),\s*price:(\d+)\}/g)].map(m => ({ y: +m[1], цена: +m[2] }));
[100, 1000, 10000, 100000].forEach(v => {
  let y = BASE; BOOSTS.forEach(b => { if (v >= b.цена) y = b.y; });
  const вдень = v * y / 100;
  о.замечание('вклад ' + String(v).padStart(6) + ' ★ → ' + y.toFixed(2) + '%/день, окупается за ' +
    Math.ceil(v / вдень) + ' дн, за год ×' + (вдень * 365 / v).toFixed(1));
});
о.замечание('Майнинг создаёт звёзды из ничего и ничем не ограничен по времени —');
о.замечание('при настоящих деньгах это обязательства, которые нечем закрыть.');

process.exit(о.итог() ? 0 : 1);
